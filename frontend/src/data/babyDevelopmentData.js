/**
 * Get development content for a given pregnancy week.
 * Returns weekly data if available, or trimester fallback.
 */
export function getDevelopmentForWeek(week, language = 'hi') {
  if (!week || week < 4) {
    return {
      isEarly: true,
      message: language === 'hi'
        ? 'गर्भावस्था के शुरुआती दिन। सही पोषण और आराम बहुत ज़रूरी है।'
        : 'Very early in pregnancy. Focus on good nutrition and rest.',
      trimester: 1
    };
  }

  const weekData = weeklyDevelopment[week] || weeklyDevelopment[Math.min(week, 40)];
  const trimester = week <= 13 ? 1 : week <= 27 ? 2 : 3;
  const fallback = trimesterFallback[trimester];

  if (!weekData) {
    return {
      isFallback: true,
      trimester,
      ...fallback[language === 'hi' ? 'hi' : 'en']
    };
  }

  return {
    week,
    trimester,
    size: weekData.size,
    comparison: language === 'hi' ? weekData.comparisonHi : weekData.comparison,
    highlight: language === 'hi' ? weekData.highlightHi : weekData.highlight,
    disclaimer: language === 'hi'
      ? '* ये अनुमानित आकार हैं और इनसे शिशु के वास्तविक स्वास्थ्य की पुष्टि नहीं होती।'
      : '* Approximate size comparison only. Does not indicate actual fetal size or health.'
  };
}
